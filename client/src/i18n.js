const exact = new Map(); const pats = [];
if (IDX[LANG]) {
  for (const r of ROWS) {
    const t = r[IDX[LANG]]; if (!t) continue;
    if (r[0].includes('{}')) pats.push([new RegExp('^' + r[0].replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replaceAll('\\{\\}', '(.+?)') + '$'), t]);
    else exact.set(r[0], t);
  }
}
export const tr = (s) => {
  if (!IDX[LANG] || !s) return s;
  const core = s.trim(); if (!core) return s;
  let out = exact.get(core);
  if (out === undefined && core.endsWith('?')) { const t = exact.get(core.slice(0, -1)); if (t !== undefined) out = t + '?'; }
  if (out === undefined) for (const [re, t] of pats) { const m = re.exec(core); if (m) { const g = m.slice(1); out = t.replace(/\{\}/g, () => tr(g.shift())); break; } }
  return out === undefined ? s : s.replace(core, out);
};

// Пользовательский текст (сообщения, имена, превью) не переводим.
const SKIP = '.txt,.nm,.bignm,.quote,.lt,.sr,.who,textarea,script,style';
const skipEl = (el) => { const hit = el?.closest?.(SKIP); return hit && !(hit.matches('.nm') && hit.textContent.trim() === 'Избранное'); };
const fix = (n) => {
  if (n.nodeType === 3) { if (!skipEl(n.parentElement)) { const v = tr(n.nodeValue); if (v !== n.nodeValue) n.nodeValue = v; } return; }
  if (n.nodeType !== 1) return;
  for (const a of ['placeholder', 'title']) {
    const cur = n.getAttribute?.(a);
    if (cur) { const v = tr(cur); if (v !== cur) n.setAttribute(a, v); }
  }
  n.childNodes.forEach(fix);
};
export function startI18n() {
  if (!IDX[LANG]) return;
  document.documentElement.lang = LANG;
  for (const f of ['alert', 'confirm', 'prompt']) { const o = window[f].bind(window); window[f] = (m, d) => o(tr(String(m)), d); }
  new MutationObserver((list) => {
    for (const m of list) { if (m.type === 'childList') m.addedNodes.forEach(fix); else fix(m.target); }
  }).observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ['placeholder', 'title'] });
  fix(document.body);
}
